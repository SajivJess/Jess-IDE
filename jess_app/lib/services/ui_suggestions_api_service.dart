import 'dart:convert';
import 'package:http/http.dart' as http;
import 'auth_api_service.dart';

class UiSuggestionModel {
  final String id;
  final String prompt;
  final String model;
  final String? imageDataUri;
  final String? previewUrl;
  final String? note;
  final DateTime createdAt;

  UiSuggestionModel({
    required this.id,
    required this.prompt,
    required this.model,
    this.imageDataUri,
    this.previewUrl,
    this.note,
    DateTime? createdAt,
  }) : createdAt = createdAt ?? DateTime.now();

  factory UiSuggestionModel.fromJson(Map<String, dynamic> json) {
    return UiSuggestionModel(
      id: json['id'] as String? ?? '',
      prompt: json['prompt'] as String? ?? '',
      model: json['model'] as String? ?? 'muse-image-1.0',
      imageDataUri: json['image_data_uri'] as String?,
      previewUrl: json['preview_url'] as String?,
      note: json['note'] as String?,
    );
  }
}

class UiSuggestionsApiService {
  static final http.Client _client = http.Client();

  static Map<String, String> _headers(String? token) => {
        'Content-Type': 'application/json',
        if (token != null && token.isNotEmpty) 'Authorization': 'Bearer $token',
      };

  /// Request a visual UI design mockup suggestion generated by Muse Image (muse-image-1.0)
  static Future<UiSuggestionModel?> generateUiSuggestion({
    required String projectId,
    required String prompt,
    String? referenceImage,
  }) async {
    try {
      final token = await AuthApiService.getToken();
      final url = Uri.parse('${AuthApiService.baseUrl}/projects/$projectId/ui-suggestions');

      final body = jsonEncode({
        'prompt': prompt,
        if (referenceImage != null) 'reference_image': referenceImage,
      });

      final res = await _client
          .post(url, headers: _headers(token), body: body)
          .timeout(const Duration(seconds: 90));

      if (res.statusCode == 200) {
        final json = jsonDecode(res.body) as Map<String, dynamic>;
        return UiSuggestionModel.fromJson(json);
      }
      return null;
    } catch (_) {
      return null;
    }
  }
}
